#!/usr/bin/env python3
"""Local SimpleStories subset with train/dev separated by source completion (EXP-0045, v2).

SimpleStories generation ids read ``<completion hash>-<story index>``, and one model completion holds several
stories written from the same prompt. The first pilot builder (kept unchanged, because its hash is recorded with
the pilot) split on the full id, so stories of one completion could land on both sides. This version splits on the
completion hash. The source stays a candidate in the registry: exploratory local use only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from slm.runlog import sha256_file, write_json  # imports torch: on Windows it must load before pyarrow (WinError 1114)

import pyarrow.parquet as pq

REVISION = "e63b8adc3b1a1bdc7cac5b500d150b71346b0628"
REPO = "SimpleStories/SimpleStories"


def completion_group(generation_id: str) -> str:
    """Completion hash of a ``<hash>-<index>`` id; an id without a numeric suffix is its own group."""
    head, separator, tail = generation_id.rpartition("-")
    return head if separator and head and tail.isdigit() else generation_id


def bucket(key: str) -> int:
    return int.from_bytes(hashlib.sha256(key.encode()).digest()[:8], "big") % 100


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parquet", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--max-train", type=int, default=60_000)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    train_path, dev_path, trace_path = (args.out / n for n in ("train.jsonl", "dev.jsonl", "provenance.jsonl"))
    counts = {"train": 0, "dev": 0, "invalid": 0}
    seen: set[str] = set()
    enough = lambda: counts["train"] >= args.max_train and counts["dev"] >= max(500, args.max_train // 20)
    with train_path.open("w", encoding="utf-8") as train, dev_path.open("w", encoding="utf-8") as dev, trace_path.open("w", encoding="utf-8") as trace:
        source_row = -1
        for batch in pq.ParquetFile(args.parquet).iter_batches(columns=["story", "generation_id", "model"], batch_size=4096):
            for row in batch.to_pylist():
                source_row += 1
                story, gid = row.get("story"), row.get("generation_id")
                if not isinstance(story, str) or len(story.strip()) < 80 or not gid:
                    counts["invalid"] += 1
                    continue
                gid = str(gid)
                if gid in seen:
                    continue
                seen.add(gid)
                group = completion_group(gid)
                split = "dev" if bucket(group) < 5 else "train"
                if split == "train" and counts["train"] >= args.max_train:
                    continue
                digest = hashlib.sha256(gid.encode()).hexdigest()
                record = {"id": f"{args.parquet.name}:{counts['train'] + counts['dev']}:{digest[:16]}", "text": story}
                (dev if split == "dev" else train).write(json.dumps(record, ensure_ascii=False) + "\n")
                trace.write(json.dumps({"source_repo": REPO, "source_revision": REVISION, "source_file": args.parquet.name,
                                        "source_row": source_row, "generation_id": gid, "completion_group": group,
                                        "generator_model": row.get("model"), "split": split,
                                        "source_text_sha256": hashlib.sha256(story.encode()).hexdigest()}, ensure_ascii=False) + "\n")
                counts[split] += 1
                if enough():
                    break
            if enough():
                break
    write_json(args.out / "manifest.json", {
        "kind": "slm.exp0045.simple_stories_pilot_v2",
        "status": "exploratory; source remains candidate; local pilot only",
        "source_repo": REPO, "source_revision": REVISION,
        "declared_license": "MIT (dataset card); generated by GPT-4o-mini-2024-07-18 per paper",
        "source_parquet": str(args.parquet), "source_parquet_sha256": sha256_file(args.parquet),
        "sampling": "shard order, one record per generation_id, SHA-256 bucket split on the completion hash, capped train docs",
        "split_group": "completion hash (generation_id without its numeric story index)",
        "exploratory_unapproved_source_override": True,
        "counts": counts,
        "files_sha256": {p.name: sha256_file(p) for p in (train_path, dev_path, trace_path)},
        "limitations": ["only the first pinned train shard is used", "not a rights approval or release dataset", "do not claim corpus-wide performance"],
    })
    print(json.dumps(counts, sort_keys=True))


if __name__ == "__main__":
    main()
