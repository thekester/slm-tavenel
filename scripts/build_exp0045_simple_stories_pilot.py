#!/usr/bin/env python3
"""Create a deterministic, provenance-preserving local pilot subset from pinned SimpleStories.

This is explicitly exploratory: the source remains a candidate in the project registry. It writes
only records selected by a stable generation_id hash, and keeps source shard/row and raw-text hash.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import pyarrow.parquet as pq

from slm.runlog import sha256_file, write_json

REVISION = "e63b8adc3b1a1bdc7cac5b500d150b71346b0628"
REPO = "SimpleStories/SimpleStories"


def bucket(key: str) -> int:
    return int.from_bytes(hashlib.sha256(key.encode()).digest()[:8], "big") % 100


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--parquet", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--max-train", type=int, default=60_000)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    train_path, dev_path, trace_path = (args.out / n for n in ("train.jsonl", "dev.jsonl", "provenance.jsonl"))
    counts = {"train": 0, "dev": 0, "invalid": 0}
    seen: set[str] = set()
    with train_path.open("w", encoding="utf-8") as train, dev_path.open("w", encoding="utf-8") as dev, trace_path.open("w", encoding="utf-8") as trace:
        parquet = pq.ParquetFile(args.parquet)
        source_row = 0
        for batch in parquet.iter_batches(columns=["story", "generation_id", "model"], batch_size=4096):
            rows = batch.to_pylist()
            for row in rows:
                current_row = source_row
                source_row += 1
                story = row.get("story")
                gid = row.get("generation_id")
                if not isinstance(story, str) or len(story.strip()) < 80 or not gid:
                    counts["invalid"] += 1
                    continue
                gid = str(gid)
                if gid in seen:
                    continue
                seen.add(gid)
                h = hashlib.sha256(gid.encode()).hexdigest()
                split = "dev" if bucket(gid) < 5 else "train"
                if split == "train" and counts["train"] >= args.max_train:
                    continue
                # The source row index is reconstructed in the source shard by iteration order.
                record = {"id": f"{args.parquet.name}:{counts['train'] + counts['dev']}:{h[:16]}", "text": story}
                (dev if split == "dev" else train).write(json.dumps(record, ensure_ascii=False) + "\n")
                trace.write(json.dumps({
                    "source_repo": REPO, "source_revision": REVISION,
                    "source_file": args.parquet.name, "source_row": current_row, "generation_id": gid,
                    "generator_model": row.get("model"), "split": split,
                    "source_text_sha256": hashlib.sha256(story.encode()).hexdigest(),
                }, ensure_ascii=False) + "\n")
                counts[split] += 1
                if counts["train"] >= args.max_train and counts["dev"] >= max(500, args.max_train // 20):
                    break
            if counts["train"] >= args.max_train and counts["dev"] >= max(500, args.max_train // 20):
                break
    write_json(args.out / "manifest.json", {
        "kind": "slm.exp0045.simple_stories_cpu_pilot",
        "status": "exploratory; source remains candidate; local pilot only",
        "source_repo": REPO, "source_revision": REVISION,
        "declared_license": "MIT (dataset card); generated by GPT-4o-mini-2024-07-18 per paper",
        "source_parquet": str(args.parquet), "source_parquet_sha256": sha256_file(args.parquet),
        "sampling": "first stable generation_id per source shard, SHA-256 bucket split, capped train docs",
        "exploratory_unapproved_source_override": True,
        "counts": counts,
        "files_sha256": {p.name: sha256_file(p) for p in (train_path, dev_path, trace_path)},
        "limitations": ["only the first pinned train shard is used", "not a rights approval or release dataset", "do not claim corpus-wide performance"],
    })
    print(json.dumps(counts, sort_keys=True))


if __name__ == "__main__":
    main()
